export function translator(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return (key, vars = {}) => {
    let s = dict[key] ?? STRINGS.en[key] ?? key;
    if (typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
